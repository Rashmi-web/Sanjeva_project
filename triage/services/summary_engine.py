def generate_summary(case, analysis):
    summary = f"""
SANJEVA STRUCTURED CASE SUMMARY

Patient ID: {case.patient_id}
Age: {case.age}
Gender: {case.gender or "Not provided"}
Preferred Language: {case.language}

Reported Symptoms:
{case.symptoms}

Symptom Duration:
{case.symptom_duration or "Not provided"}

Potential Urgency Category:
{analysis["priority"]}

Reason:
{analysis["priority_reason"]}

Missing Information:
{", ".join(analysis["missing_information"]) if analysis["missing_information"] else "No obvious missing field detected"}

Follow-Up Questions:
"""

    for question in analysis["follow_up_questions"]:
        summary += f"\n- {question}"

    summary += """

Reviewer Notice:
This summary is generated by a prototype triage-support system.
It is not a medical diagnosis or prescription. Final assessment
and decisions must be made by qualified healthcare professionals.
"""

    return summary